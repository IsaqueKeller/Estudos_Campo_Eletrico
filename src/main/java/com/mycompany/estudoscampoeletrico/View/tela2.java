    private void btnValoresCargaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnValoresCargaActionPerformed
    try {
        Carga c = new Carga();
        c.setDistanciaEixoX(Double.parseDouble(edtPosicaoX.getText()));
        c.setDistanciaEixoY(Double.parseDouble(edtPosicaoY.getText()));
        c.setValorDaCarga(Double.parseDouble(edtValorCarga.getText()));
        cargas.add(c);
        
        edtPosicaoX.setText("");
        edtPosicaoY.setText("");
        edtValorCarga.setText("");
    } catch(NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Digite apenas números válidos.");
        }
    }//GEN-LAST:event_btnValoresCargaActionPerformed

